def _check_mean_and_std_length(labels: Sequence[int], means: Sequence[TypeRangeFloat] | None, stds: Sequence[TypeRangeFloat] | None) -> None:
    num_labels = len(labels)
    if means is not None:
        num_means = len(means)
        message = f'"mean" must define a value for each label but length of "mean" is {num_means} while {num_labels} labels were found'
        if num_means != num_labels:
            raise RuntimeError(message)
    if stds is not None:
        num_stds = len(stds)
        message = f'"std" must define a value for each label but length of "std" is {num_stds} while {num_labels} labels were found'
        if num_stds != num_labels:
            raise RuntimeError(message)

class OneHot(LabelTransform):
    """Reencode label maps using one-hot encoding.

    Args:
        num_classes: See :func:`~torch.nn.functional.one_hot`.
        **kwargs: See :class:`~torchio.transforms.Transform` for additional
            keyword arguments.
    """

    def __init__(self, num_classes: int=-1, **kwargs):
        super().__init__(**kwargs)
        self.num_classes = num_classes
        self.args_names = ['num_classes']
        self.invert_transform = False

    def apply_transform(self, subject):
        for image in self.get_images(subject):
            if self.invert_transform:
                self.argmax(image)
            else:
                self.one_hot(image)
        return subject

    @staticmethod
    def argmax(image: Image) -> None:
        data = image.data.argmax(dim=0, keepdim=True)
        image.set_data(data)

    def one_hot(self, image: Image) -> None:
        if image.num_channels > 1:
            message = f'The number of input channels must be 1, but it is {image.num_channels}'
            raise RuntimeError(message)
        data = image.data[0]
        num_classes = -1 if self.num_classes is None else self.num_classes
        one_hot = F.one_hot(data.long(), num_classes=num_classes)
        image.set_data(one_hot.permute(3, 0, 1, 2).type(data.type()))

