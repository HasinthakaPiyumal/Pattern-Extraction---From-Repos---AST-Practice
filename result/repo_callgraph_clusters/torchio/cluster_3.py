        def padding_func():
            return
        for padding_mode in [0, *tio.Pad.PADDING_MODES, padding_func]:
            tio.Pad(0, padding_mode=padding_mode)
        with self.assertRaises(KeyError):
            tio.Pad(0, padding_mode='abc')

